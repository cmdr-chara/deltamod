'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { inventory } = require('./desktop-benchmark/package-footprint.cjs');
const MEDIA = /\.(?:mp3|wav|ogg|mp4|webm)$/i;
const TEXT = /\.(?:js|css|html)$/i;
const SOURCE_ONLY = /(?:^|\/)(?:components|types)(?:\/|$)|\.(?:tsx?|jsx|map|md)$/i;
const ENTRY_ONLY = new Set(['boot-native-entry.js', 'modules/boot-native.mjs', 'jsconfig.json']);

function isThemeMedia(relative) {
    return relative.startsWith('themes/') && MEDIA.test(relative);
}

function directThemeReferences(files, sourceRoot) {
    const keep = new Set();
    for (const file of files) {
        if (!TEXT.test(file.path) || SOURCE_ONLY.test(file.path) || ENTRY_ONLY.has(file.path) || file.path === 'tauri-adapter.js') continue;
        const text = fs.readFileSync(path.join(sourceRoot, file.path), 'utf8');
        const expression = /(?:\.\.?\/)*(?:web\/)?themes\/[^\s'"`<>)]*/g;
        for (const match of text.matchAll(expression)) {
            const before = text.slice(Math.max(0, match.index - 100), match.index);
            // These paths are generated by the validated Tauri asset URL adapter.
            if (/assetUrl\(\s*['"]app['"]\s*,\s*[`'"][^`'"]*$/.test(before)) continue;
            const relative = match[0].slice(match[0].indexOf('themes/'));
            const dynamic = relative.search(/\$\{|\+|\?/);
            const literal = dynamic === -1 ? relative : relative.slice(0, dynamic);
            if (MEDIA.test(literal) || literal.endsWith('/')) keep.add(literal);
        }
    }
    return [...keep];
}

function stageFrontend(projectRoot = path.resolve(__dirname, '..')) {
    const source = path.join(projectRoot, 'web');
    const dist = path.join(projectRoot, 'dist');
    const output = path.join(dist, 'frontend');
    for (const directory of [source, dist, output]) {
        if (fs.existsSync(directory) && fs.lstatSync(directory).isSymbolicLink()) {
            throw new Error('Frontend staging refuses a linked directory');
        }
    }
    const original = inventory(source);
    for (const required of ['index.html', 'boot/deltamod-boot.js', 'boot/deltamod-boot.css']) {
        if (!original.files.some(file => file.path === required && file.bytes > 0)) {
            throw new Error(`Build the boot bundle before staging: missing ${required}`);
        }
    }
    const retainedReferences = directThemeReferences(original.files, source);
    fs.mkdirSync(dist, { recursive: true });
    fs.rmSync(output, { recursive: true, force: true });
    fs.mkdirSync(output);
    let externalThemeMediaBytes = 0;
    let developmentBytes = 0;
    let retainedMediaBytes = 0;
    for (const file of original.files) {
        if (SOURCE_ONLY.test(file.path) || ENTRY_ONLY.has(file.path) || file.path.split('/').some(part => part.startsWith('.'))) {
            developmentBytes += file.bytes;
            continue;
        }
        if (isThemeMedia(file.path)) {
            const directlyReferenced = retainedReferences.some(reference => reference.endsWith('/')
                ? file.path.startsWith(reference) : file.path === reference);
            if (!directlyReferenced) {
                externalThemeMediaBytes += file.bytes;
                continue;
            }
            retainedMediaBytes += file.bytes;
        }
        const target = path.join(output, file.path);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.copyFileSync(path.join(source, file.path), target);
    }
    const htmlPath = path.join(output, 'index.html');
    const html = fs.readFileSync(htmlPath, 'utf8');
    if (!html.includes('<html ')) throw new Error('Frontend root element missing');
    fs.writeFileSync(htmlPath, html.replace('<html ', '<html data-deltamod-external-theme-media="true" '));
    const staged = inventory(output);
    const report = {
        schemaVersion: 1,
        sourceBytes: original.bytes,
        embeddedFrontendBytes: staged.bytes,
        externalThemeMediaBytes,
        developmentBytes,
        retainedMediaBytes,
        retainedReferences,
        note: 'External theme media stays in the complete bundled themes resource. No user theme or native tool is removed.'
    };
    fs.writeFileSync(path.join(dist, 'frontend-footprint.json'), `${JSON.stringify(report, null, 2)}\n`);
    console.log(`Staged frontend: ${staged.bytes} bytes; ${externalThemeMediaBytes} media bytes kept only as external resources.`);
    return report;
}
if (require.main === module) stageFrontend();
module.exports = { stageFrontend, directThemeReferences, isThemeMedia };
