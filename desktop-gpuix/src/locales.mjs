export const dictionaries = Object.freeze({ en, it });
export function normalizeLocale(locale) {
  return typeof locale === 'string' && locale.toLowerCase().split(/[-_]/)[0] === 'it' ? 'it' : 'en';
}
export function placeholders(template) {
  return [...new Set([...template.matchAll(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g)].map(match => match[1]))].sort();
}
export function translate(locale, key, values = {}) {
  const language = dictionaries[normalizeLocale(locale)];
  const template = Object.hasOwn(language, key) ? language[key] : Object.hasOwn(en, key) ? en[key] : key;
  // One substitution pass. A user's mod name containing braces is data, not
  // another translation/template expression. Output is always plain text.
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (match, name) => {
    if (!Object.hasOwn(values, name) || !['string', 'number'].includes(typeof values[name])) return match;
    return String(values[name]);
  });
}
const formats = { en: new Intl.NumberFormat('en', { maximumFractionDigits: 2 }),
  it: new Intl.NumberFormat('it', { maximumFractionDigits: 2 }) };
export function formatBytes(locale, bytes) {
  if (!Number.isSafeInteger(bytes) || bytes < 0) return translate(locale, 'Unknown size');
  const unit = bytes === 0 ? 0 : Math.min(4, Math.floor(Math.log(bytes) / Math.log(1024)));
  return `${formats[normalizeLocale(locale)].format(bytes / 1024 ** unit)} ${['B', 'KiB', 'MiB', 'GiB', 'TiB'][unit]}`;
}
