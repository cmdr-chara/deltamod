function prefersReducedMotion() {
    return window.matchMedia('(prefers-reduced-motion: reduce)').matches;
}

function releaseAudioBuffer() {
    rememberMenuAudioPosition();
    audio.pause();
    audio.currentTime = 0;
    audio.removeAttribute('src');
    audio.load();
    currentAudio = "";
    currentAudioSource = "";
}

function rememberMenuAudioPosition() {
    if (currentAudioSource && Number.isFinite(audio.currentTime)) {
        menuAudioPositions.set(currentAudioSource, audio.currentTime);
    }
}

function configureMenuAudioPlayback(source) {
    const themeSource = theme?.mainSong
        ? themeAssetUrl(theme, 'mus', theme.mainSong)
        : '';
    const isThemeTrack = source === themeSource;
    const configuredRate = isThemeTrack ? Number(theme?.musicPlaybackRate) : 1;
    const playbackRate = Number.isFinite(configuredRate)
        ? Math.min(2, Math.max(0.5, configuredRate))
        : 1;

    audio.defaultPlaybackRate = playbackRate;
    audio.playbackRate = playbackRate;
    if ('preservesPitch' in audio) {
        audio.preservesPitch = isThemeTrack
            ? theme?.musicPreservesPitch !== false
            : true;
    }
}

function switchMenuAudioSource(source) {
    rememberMenuAudioPosition();
    audio.pause();

    const resumeAt = menuAudioPositions.get(source) || 0;
    currentAudioSource = source;
    audio.src = source;
    configureMenuAudioPlayback(source);

    const restorePosition = () => {
        if (currentAudioSource !== source) return;

        const latestResumeAt = menuAudioPositions.get(source) || resumeAt;
        const maximumPosition = Number.isFinite(audio.duration)
            ? Math.max(0, audio.duration - 0.44)
            : latestResumeAt;
        audio.currentTime = Math.min(latestResumeAt, maximumPosition);
    };

    if (audio.readyState >= 1) {
        restorePosition();
    } else {
        audio.addEventListener('loadedmetadata', restorePosition, { once: true });
    }
}

function loopMenuAudio() {
    const loopBuffer = 0.44;
    if (Number.isFinite(audio.duration) && audio.currentTime > audio.duration - loopBuffer) {
        audio.currentTime = 0;
        audio.play().catch(() => {});
    }
}

audio.addEventListener('timeupdate', loopMenuAudio);

function themeUsesIntegratedVideoAudio(themeConfig = theme) {
    return Boolean(
        themeConfig?.backgroundVideo
        && themeConfig?.videoHasAudio
        && !themeVideoFallbackActive
    );
}

function getThemeBackgroundVideo() {
    return document.getElementById('theme-background-video');
}

function themeVideoUrl(themeConfig = theme) {
    if (!themeConfig?.backgroundVideo) return '';
    return themeAssetUrl(themeConfig, 'video', themeConfig.backgroundVideo);
}

function setThemeVideoAudioEnabled(enabled) {
    const video = getThemeBackgroundVideo();
    if (!video || !themeUsesIntegratedVideoAudio()) return;
    video.muted = !enabled;
    video.volume = enabled ? TARGET_MUSIC_VOLUME : 0;
    if (video.src && video.paused) {
        video.play().catch(() => {});
    }
}

function suspendThemeBackgroundVideo() {
    const video = getThemeBackgroundVideo();
    if (!video?.src || !theme?.backgroundVideo) return;

    suspendedThemeVideo = {
        source: video.dataset.source,
        currentTime: Number.isFinite(video.currentTime) ? video.currentTime : 0
    };
    video.pause();
    video.volume = 0;
}

function resumeThemeBackgroundVideo(audioEnabled) {
    const video = getThemeBackgroundVideo();
    const expectedSource = themeVideoUrl();
    if (!video || !suspendedThemeVideo || suspendedThemeVideo.source !== expectedSource) {
        return false;
    }

    const resumeAt = suspendedThemeVideo.currentTime;
    suspendedThemeVideo = null;
    video.muted = !audioEnabled;
    video.volume = audioEnabled ? TARGET_MUSIC_VOLUME : 0;

    const resumePlayback = () => {
        const maximumPosition = Number.isFinite(video.duration)
            ? Math.max(0, video.duration - 0.44)
            : resumeAt;
        const targetTime = Math.min(resumeAt, maximumPosition);
        if (Math.abs(video.currentTime - targetTime) > 0.05) {
            video.currentTime = targetTime;
        }
        video.play().catch(() => {});
    };

    if (video.readyState >= HTMLMediaElement.HAVE_METADATA) {
        resumePlayback();
    } else {
        video.addEventListener('loadedmetadata', resumePlayback, { once: true });
    }
    return true;
}

function scheduleThemeVideoSuspension() {
    clearTimeout(themeVideoSuspendTimer);
    const video = getThemeBackgroundVideo();
    if (video?.src) {
        suspendThemeBackgroundVideo();
    }
}

function applyThemeBackground() {
    const background = document.querySelector('.bg');
    const video = getThemeBackgroundVideo();
    if (!background || !video) return;

    background.style.backgroundImage = `url("${themeAssetUrl(theme, 'img', theme.background)}")`;
    if (!theme.backgroundVideo) {
        clearTimeout(themeVideoSuspendTimer);
        clearTimeout(themeVideoLoadTimer);
        suspendedThemeVideo = null;
        themeVideoFallbackActive = false;
        video.pause();
        video.hidden = true;
        video.removeAttribute('src');
        video.removeAttribute('poster');
        video.removeAttribute('data-source');
        video.load();
        return;
    }

    const source = themeVideoUrl();
    clearTimeout(themeVideoLoadTimer);
    themeVideoFallbackActive = false;
    video.poster = themeAssetUrl(theme, 'img', theme.background);
    video.hidden = true;
    video.loop = true;
    video.onplaying = () => {
        clearTimeout(themeVideoLoadTimer);
        video.hidden = false;
        background.style.backgroundImage = 'none';
    };
    video.onerror = () => {
        void fallBackFromThemeVideo(video, background, `media error ${video.error?.code || 'unknown'}`);
    };
    if (video.dataset.source !== source) {
        suspendedThemeVideo = null;
        video.muted = true;
        video.volume = 0;
        video.dataset.source = source;
        video.src = source;
    }
    video.play().catch(error => {
        void fallBackFromThemeVideo(video, background, error?.name || 'playback rejected');
    });
    const themeVideoReadyTimeout = window.DeltamodLinuxCompat?.isLinuxTauri
        && window.DeltamodLinuxCompat.getMode?.() === 'quality'
        ? 20000
        : 5000;
    themeVideoLoadTimer = setTimeout(() => {
        if (video.readyState < HTMLMediaElement.HAVE_FUTURE_DATA) {
            void fallBackFromThemeVideo(video, background, 'load timeout');
        }
    }, themeVideoReadyTimeout);
}

async function fallBackFromThemeVideo(video, background, reason) {
    if (themeVideoFallbackActive || video.dataset.source !== themeVideoUrl()) return;
    themeVideoFallbackActive = true;
    clearTimeout(themeVideoLoadTimer);
    video.pause();
    video.hidden = true;
    video.removeAttribute('src');
    video.removeAttribute('data-source');
    video.load();
    background.style.backgroundImage = `url("${themeAssetUrl(theme, 'img', theme.background)}")`;
    console.warn(`Theme video unavailable (${reason}); using poster and audio fallback.`);

    if (await window.deltamodBackend.invoke('getUniqueFlag', ["AUDIO"])) {
        currentAudio = 'mainTheme.mp3';
        switchMenuAudioSource(themeAssetUrl(theme, 'mus', theme.mainSong));
        audio.loop = true;
        audio.volume = TARGET_MUSIC_VOLUME;
        await audio.play().catch(() => {});
    }
}

