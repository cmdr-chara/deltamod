/**
 * Navigates to a specific internal page and processes HTML/CSS injections.
 * @param {string} name - The identifier of the page to load.
 */
let activePageNavigation = null;
let queuedPageNavigation = null;
let pageNavigationDrain = null;

function page(name) {
    const forceReload = name === '';
    const target = forceReload ? pageN : name;

    if (!target) {
        return Promise.resolve(false);
    }

    if (!forceReload && (
        target === activePageNavigation ||
        target === queuedPageNavigation?.target
    )) {
        return Promise.resolve(false);
    }

    const navigation = new Promise((resolve, reject) => {
        if (queuedPageNavigation) {
            queuedPageNavigation.resolve(false);
        }
        queuedPageNavigation = { target, resolve, reject };
    });

    schedulePageNavigationDrain();

    return navigation;
}

function schedulePageNavigationDrain() {
    if (pageNavigationDrain) return;

    pageNavigationDrain = drainPageNavigations().finally(() => {
        pageNavigationDrain = null;
        if (queuedPageNavigation) {
            schedulePageNavigationDrain();
        }
    });
}

async function drainPageNavigations() {
    while (queuedPageNavigation) {
        const navigation = queuedPageNavigation;
        queuedPageNavigation = null;
        activePageNavigation = navigation.target;

        try {
            await renderPage(navigation.target);
            navigation.resolve(true);
        } catch (error) {
            window.DeltamodUI.showError(document.querySelector('.viewport'), error, () => page(navigation.target));
            navigation.reject(error);
        } finally {
            activePageNavigation = null;
        }
    }
}

async function renderPage(name) {
    if (name === '') name = pageN;
    if (!PAGE_REGISTRY[name]) throw new Error(`Blocked unknown page: ${String(name)}`);
    const previousFocus = document.activeElement;
    const focusContent = Boolean(previousFocus?.matches?.('.sidebar-button:focus-visible'));
    rew();

    // Clear existing intervals/listeners to prevent memory leaks
    try {
        window._intervals.forEach(clearInterval);
    } catch(e) {
        console.log('No intervals to clear');
    }
    window._intervals = [];

    window._eventListeners = window._eventListeners || [];
    window._eventListeners.forEach(({ element, event, handler }) => {
        element.removeEventListener(event, handler);
    });
    window._eventListeners = [];

    window._onClosePage = window._onClosePage || [];
    window._onClosePage.forEach(func => func());
    window._onClosePage = [];

    if (currentPageScript) {
        currentPageScript.remove();
        currentPageScript = null;
    }

    if (addedStyle) {
        addedStyle.remove();
        addedStyle = null;
    }
    
    if (name == "") {
        name = pageN;
    }

    // Prevents escaping to home if game is baked
    if (name === 'main' && PAGE_REGISTRY.bakedhome && await window.deltamodBackend.invoke('isBaked', [])) {
        name = 'bakedhome';
    }
    const pageDefinition = PAGE_REGISTRY[name];
    if (!pageDefinition) {
        throw new Error(`Blocked unknown page: ${String(name)}`);
    }

    // Keep navigation immediate. Animating the full viewport promotes every
    // blurred panel to a large compositor surface and retains substantial GPU
    // memory after each page change.
    const viewport = document.querySelector('.viewport');
    viewport.style.animation = 'none';
    window.deltamodBackend.invoke('showWindow', []);

    // Load theme if not yet initialized
    if (!theme) {
        await themeRefresh(false); 
    }

    window.currentPageStack = {};

    // Process Page HTML
    var purifiedHTML = await loadPageMarkup(pageDefinition);
    await window.Localization?.ready;
    purifiedHTML = window.Localization?.replaceTokens(purifiedHTML) || purifiedHTML;
    
    var runScripts = false;
    var changeAudio = false;

    // Detect and queue JS execution
    if (purifiedHTML.includes('JSL')) {
        purifiedHTML = purifiedHTML.replace('JSL', '');
        runScripts = true;
    }

    // Load internal stylesheet tags
    if (purifiedHTML.includes('STYLESHEET[')) {
        var stylesheetSrc = purifiedHTML.match(/STYLESHEET\[(.*?)\]/);
        if (stylesheetSrc && stylesheetSrc[1]) {
            if (addedStyle) addedStyle.remove();
            addedStyle = document.createElement('link');
            addedStyle.rel = 'stylesheet';
            addedStyle.dataset.pageStylesheet = name;
            if (pageDefinition.stylesheet) {
                addedStyle.href = pageDefinition.stylesheet;
            } else {
                if (!/^[a-z0-9_-]+$/i.test(stylesheetSrc[1])) {
                    throw new Error(`Blocked unsafe stylesheet name on page ${name}.`);
                }
                addedStyle.href = `${pageDefinition.base}${stylesheetSrc[1]}.css`;
            }
            document.getElementById('head').appendChild(addedStyle);
        }
        purifiedHTML = purifiedHTML.replace(/STYLESHEET\[(.*?)\]/g, '');
    } else if (addedStyle) {
        addedStyle.remove();
        addedStyle = null;
    }

    // Handle NO-SIDEBAR tag
    if (purifiedHTML.includes('NO-SIDEBAR')) {
        purifiedHTML = purifiedHTML.replace('NO-SIDEBAR', '');
        ([...Array.from(document.getElementsByClassName('sidebar-button')), ...Array.from(document.getElementsByClassName('gamebanana-account'))]).forEach(button => { button.setAttribute('data-disabled', 'true'); button.setAttribute('aria-disabled', 'true'); if (button.tagName === 'BUTTON') button.disabled = true; });
    } else {
        ([...Array.from(document.getElementsByClassName('sidebar-button')), ...Array.from(document.getElementsByClassName('gamebanana-account'))]).forEach(button => { button.setAttribute('data-disabled', 'false'); button.setAttribute('aria-disabled', 'false'); if (button.tagName === 'BUTTON') button.disabled = false; });
    }

    // Extract Title Tag
    var title = purifiedHTML.match(/TITLE\[(.*?)\]/);
    purifiedHTML = purifiedHTML.replace(/TITLE\[(.*?)\]/g, '');
    const pageTitle = window.Localization?.translateKnownText(
        title?.[1] || 'Deltamod Community'
    ) || title?.[1] || 'Deltamod Community';
    const pageTitleElement = document.getElementById('pageTitle');
    if (pageTitleElement) {
        pageTitleElement.textContent = pageTitle;
    }

    // Extract Exclude Audio Tag
    var themeAudioExclude = purifiedHTML.match(/THEME-AUDIO-EXCLUDE\[(.*?)\]/);
    purifiedHTML = purifiedHTML.replace(/THEME-AUDIO-EXCLUDE\[(.*?)\]/g, '');

    // Process Audio Tag
    if (true) {
        var audioSrc = purifiedHTML.match(/AUDIO\[(.*?)\]/);
        console.log('Audio source found:' + audioSrc);
        
        if (!audioSrc || !audioSrc[1]) {
            audioSrc = ['AUDIO[mainTheme.mp3]', 'mainTheme.mp3'];
        }
        if (theme.id == themeAudioExclude?.[1]) {
            audioSrc = ['AUDIO[mainTheme.mp3]', 'mainTheme.mp3'];
        }
        const [dynamicMusic, shouldPlayAudio] = await Promise.all([
            window.deltamodBackend.invoke('getUniqueFlag', ["DYNAMUSIC"]),
            window.deltamodBackend.invoke('getUniqueFlag', ["AUDIO"])
        ]);
        if (dynamicMusic == false) {
            audioSrc = ['AUDIO[mainTheme.mp3]', 'mainTheme.mp3'];
        }

        if (themeUsesIntegratedVideoAudio()) {
            releaseAudioBuffer();
            setThemeVideoAudioEnabled(shouldPlayAudio);
        } else if (!shouldPlayAudio) {
            releaseAudioBuffer();
        } else if (audioSrc?.[1] === 'mainTheme.mp3' && !theme.mainSong) {
            releaseAudioBuffer();
        } else if (audioSrc && audioSrc[1] && (audioSrc[1] !== currentAudio || !audio.src)) {
            currentAudio = audioSrc[1];
            const nextAudioSource = audioSrc[1] == 'mainTheme.mp3'
                ? themeAssetUrl(theme, 'mus', theme.mainSong)
                : './' + audioSrc[1];
            switchMenuAudioSource(nextAudioSource);

            audio.volume = TARGET_MUSIC_VOLUME;
            changeAudio = true;
        }

        if (shouldPlayAudio && !themeUsesIntegratedVideoAudio()) {
            audio.play().catch(() => {});
        }
        purifiedHTML = purifiedHTML.replace(/AUDIO\[(.*?)\]/g, '');
    }

    // Inject Viewport HTML
    const pageViewport = document.getElementsByClassName('viewport')[0];
    pageViewport.querySelectorAll('*').forEach(element => element._tippy?.destroy());
    pageViewport.querySelectorAll('img, video, source').forEach(media => {
        media.removeAttribute('src');
        media.removeAttribute('srcset');
    });
    pageViewport.dataset.page = name;
    pageViewport.innerHTML = purifiedHTML;
    window.DeltamodUI?.mount(pageViewport);
    window.Localization?.apply(pageViewport);
    window.Localization?.applyKnownText(pageViewport);

    // Set Active Sidebar Button
    ([...Array.from(document.getElementsByClassName('sidebar-button')), ...Array.from(document.getElementsByClassName('gamebanana-account'))]).forEach(button => {
        if (button.getAttribute('data-page') === (name === 'allmods-v2' ? 'allmods' : name)) {
            button.classList.add('active');
            button.setAttribute('aria-current', 'page');
        } else {
            button.classList.remove('active');
            button.removeAttribute('aria-current');
        }
    });

    // Handle Scrolling
    try {
        const vp = document.getElementsByClassName('viewport')[0];
        if (vp && typeof vp.scrollTo === 'function') {
            vp.scrollTo({ top: 0, left: 0, behavior: 'auto' });
        } else {
            window.scrollTo({ top: 0, left: 0, behavior: 'auto' });
        }
    } catch (e) {
        window.scrollTo(0, 0);
    }

    pageN = name;

    applyThemeStyles(theme);

    // Execute Page JS
    if (runScripts) {
        try {
            await loadPageScript(pageDefinition);
        } catch (error) {
            console.error('Error occurred while loading script for page:', name, error);
        }
    }

    window.Localization?.apply(pageViewport);

    const visualTheme = activeThemeVisualConfig();
    window.ThemeSprites?.apply(visualTheme.soulColor || visualTheme.color, document)
        .then(() => {
            if (document.documentElement.classList.contains('roaring-knight-awakened')) {
                setRoaringKnightSpriteSet(true);
            }
        })
        .catch(error => {
            console.warn('Unable to recolor page sprites:', error);
        });

    if (focusContent) {
        const heading = pageViewport.querySelector('h1');
        if (heading) { heading.tabIndex = -1; heading.focus({ preventScroll: true }); }
    }
    window.dispatchEvent(new CustomEvent('deltamod-page-ready', { detail: { name } }));
    await signalBenchmarkReadiness();

}

