function themeAssetUrl(themeConfig, folder, fileName) {
    if (themeConfig?.builtIn) {
        return window.deltamodBackend.assetUrl('app', `web/themes/${folder}/${fileName}`);
    }
    if (themeConfig?.runtimeLayout) {
        return window.deltamodBackend.assetUrl('theme', `${themeConfig.id}/${fileName}`);
    }
    return window.deltamodBackend.assetUrl('theme', `${folder}/${fileName}`);
}

