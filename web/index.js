/**
 * Refreshes the application theme and applies background/music.
 * @param {boolean} refreshAudio - Whether to also reload and play the main theme song.
 */
async function themeRefresh(refreshAudio = true) {
    const themeName = await window.deltamodBackend.invoke('getTheme', []);
    const themePath = `data/${themeName}.theme.json`;
    let response;
    let builtIn = false;
    let runtimeLayout = false;
    try {
        response = await fetch(window.deltamodBackend.assetUrl('theme', themePath));
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
    } catch (error) {
        try {
            response = await fetch(window.deltamodBackend.assetUrl('theme', `${themeName}/theme.json`));
            if (!response.ok) throw new Error(`HTTP ${response.status}`);
            runtimeLayout = true;
        } catch {
            response = await fetch(window.deltamodBackend.assetUrl('app', `web/themes/${themePath}`));
            if (!response.ok) throw error;
            builtIn = true;
        }
    }
    theme = await response.json();
    theme.builtIn = builtIn;
    theme.runtimeLayout = runtimeLayout;
    if (runtimeLayout) {
        theme.background = theme.background || theme.icon;
        theme.mainSong = theme.mainSong || theme.music;
        theme.description = theme.description || 'Custom theme';
        theme.musicTrack = theme.musicTrack || (theme.mainSong ? 'Custom audio' : 'No custom audio');
        theme.color = theme.color || 'rgb(205, 68, 81)';
        theme.soulColor = theme.soulColor || '#FF0000';
    }
    bootTheme(theme);
    applyThemeBackground();
    applyThemeStyles(theme);
    // The seasonal layer stays hidden until these CSS variables contain the
    // active theme, preventing a default-color flash during startup or swaps.
    window.SeasonalEvents?.setThemeReady(true);
    window.ThemeSprites?.apply(theme.soulColor || theme.color, document).catch(error => {
        console.warn('Unable to recolor theme sprites:', error);
    });
    window.ThemeSprites?.applyAppIcon(theme, window.deltamodBackend).catch(error => {
        console.warn('Unable to update the themed application icon:', error);
    });
    
    if (refreshAudio) {
        const shouldPlayAudio = await window.deltamodBackend.invoke('getUniqueFlag', ["AUDIO"]);
        if (themeUsesIntegratedVideoAudio()) {
            releaseAudioBuffer();
            setThemeVideoAudioEnabled(shouldPlayAudio);
        } else if (shouldPlayAudio && theme.mainSong) {
            audio.loop = true;
            audio.volume = TARGET_MUSIC_VOLUME;
            currentAudio = 'mainTheme.mp3';
            switchMenuAudioSource(themeAssetUrl(theme, 'mus', theme.mainSong));
            await audio.play().catch(() => {});
        } else {
            releaseAudioBuffer();
        }
    }
}

